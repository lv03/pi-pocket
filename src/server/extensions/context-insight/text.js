/** The dashboard's two languages: English, and Simplified Chinese. */

const KEY = "x.context-insight.lang";
const listeners = new Set();

function detect() {
    try {
        const stored = localStorage.getItem(KEY);

        if (stored === "zh" || stored === "en") {
            return stored;
        }
    } catch {
        // Storage can be off: follow the browser.
    }

    return String(navigator.language ?? "")
        .toLowerCase()
        .startsWith("zh")
        ? "zh"
        : "en";
}

let current = detect();

export function lang() {
    return current;
}

export function setLang(next) {
    current = next === "zh" ? "zh" : "en";

    try {
        localStorage.setItem(KEY, current);
    } catch {
        // Keep it for this page.
    }

    for (const listener of listeners) {
        listener(current);
    }
}

export function subscribeLang(listener) {
    listeners.add(listener);

    return () => listeners.delete(listener);
}

